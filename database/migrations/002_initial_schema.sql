BEGIN;

ALTER TABLE categories
    ADD COLUMN created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN updated_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN is_active BOOLEAN NOT NULL
        DEFAULT TRUE;

